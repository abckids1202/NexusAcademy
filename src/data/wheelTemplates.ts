import type { WheelTemplate } from "../types";
import { getDefaultOptionColor, getReadableTextColor } from "../utils/colors";

const createTemplateOptions = (
  items: Array<{ label: string; weight?: number; color?: string; specialType?: WheelTemplate["wheel"]["options"][number]["specialType"] }>,
): WheelTemplate["wheel"]["options"] =>
  items.map((item, index) => {
    const color = item.color ?? getDefaultOptionColor(index);

    return {
      id: `template_option_${index + 1}`,
      label: item.label,
      color,
      textColor: getReadableTextColor(color),
      weight: item.weight ?? 1,
      isActive: true,
      isRemoved: false,
      isSpecial: item.specialType ? item.specialType !== "normal" : false,
      specialType: item.specialType ?? "normal",
      sortOrder: index,
    };
  });

